const { chromium } = require('playwright');
const SP = process.argv[2] + '/v2/';
(async () => {
  const b = await chromium.launch();
  const page = await (await b.newContext({ viewport: { width: 390, height: 844 }, locale: 'ar-AE' })).newPage();
  const errors = [];
  page.on('pageerror', e => errors.push('PAGEERROR ' + e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text().slice(0, 160)); });
  const shot = n => page.screenshot({ path: SP + n + '.png' });
  const log = (k, v) => console.log(k.padEnd(44), v);
  const W = ms => page.waitForTimeout(ms);
  await page.goto('http://localhost:8099/', { waitUntil: 'networkidle' }); await W(900);
  await shot('01-login');
  await page.locator('input[inputmode="numeric"]').first().fill('501234567');
  await page.getByRole('checkbox').click();
  await page.getByRole('button', { name: 'تسجيل الدخول' }).click(); await W(300);
  await page.locator('input[inputmode="numeric"]').first().fill('1234');
  await page.getByRole('button', { name: 'تأكيد' }).click(); await W(1200);
  await shot('02-home');
  { const body = await page.locator('body').innerText(); log('home shows top-6 priority agents', ['جلال','طلال','سارة','راشد','نورة','ليلى'].every((n) => body.includes(n))); }
  await page.getByRole('button', { name: 'تحدّث مع مهرة' }).first().click(); await W(900);
  await shot('03-listening');
  await page.getByRole('button', { name: 'إيقاف' }).last().click(); await W(300);
  await page.getByRole('tab', { name: 'طلباتي' }).click(); await W(600);
  await shot('04-requests');
  await page.getByRole('button', { name: 'قارن العروض' }).click(); await W(800);
  await shot('05-offers');
  await page.getByRole('button', { name: 'اختر هذا العرض' }).click(); await W(400);
  await shot('06-offers-pick');
  await page.getByRole('button', { name: 'أكّد الاختيار' }).click(); await W(500);
  await shot('07-confirmed');
  log('confirmed screen', (await page.locator('body').innerText()).includes('تم اختيار العرض'));
  await page.getByRole('button', { name: 'رجوع' }).click(); await W(500);
  await page.getByRole('tab', { name: 'حسابي' }).click(); await W(600);
  await shot('08-profile');
  await page.getByRole('button', { name: /السيرة الذاتية.*CV/ }).click(); await W(700);
  await shot('09-cv');
  await page.getByRole('button', { name: 'رجوع' }).click(); await W(400);
  await page.getByRole('button', { name: 'إعدادات الصوت' }).first().dispatchEvent('click'); await W(700);
  await shot('10-voice');
  await page.getByRole('button', { name: 'رجوع' }).click(); await W(400);
  await page.getByRole('tab', { name: 'الوكلاء' }).click(); await W(600);
  await shot('11-specialists');
  console.log('errors', JSON.stringify(errors.slice(0, 4)));
  await b.close();
})().catch(e => { console.error('FLOW FAILED:', e.message.split('\n').slice(0, 3).join(' | ')); process.exit(1); });
